# 14. SAVE FINAL CLUSTERED DATASET
# ============================================================

final_file = os.path.join(
    OUTPUT_DIR,
    "iris_clustered.csv"
)

df_model.to_csv(
    final_file,
    index=False
)

print("\nFinal clustered dataset saved to:")
print(final_file)


# ============================================================
# 15. FINAL SUMMARY
# ============================================================

print("\n" + "=" * 75)
print("FINAL SUMMARY")
print("=" * 75)

print("Dataset: Iris")
print("Clustering features:", len(feature_columns))
print("Selected K:", K)
print(
    "K-Means silhouette:",
    round(kmeans_silhouette, 4)
)
print(
    "Hierarchical silhouette:",
    round(hierarchical_silhouette, 4)
)
print("Output directory:", OUTPUT_DIR)

print("\nClustering analysis completed successfully.")